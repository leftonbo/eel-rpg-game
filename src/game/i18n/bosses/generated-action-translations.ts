const upperCaseSegments = new Set(['ai', 'hp', 'ko', 'mp']);

function humanizeActionId(actionId: string): string {
    return actionId
        .split('-')
        .filter(Boolean)
        .map(segment => upperCaseSegments.has(segment)
            ? segment.toUpperCase()
            : segment.charAt(0).toUpperCase() + segment.slice(1)
        )
        .join(' ');
}

export const generatedActionTranslations: Record<string, BossTranslationData> = Object.fromEntries(
    Object.entries(bossActionIds).map(([bossId, actionIds]) => [
        bossId,
        {
            actions: Object.fromEntries(actionIds.map(actionId => {
                const name = humanizeActionId(actionId);
                return [actionId, {
                    name,
                    description: `Uses ${name}.`,
                    messages: [`{boss} uses ${name}!`]
                }];
            }))
        }
    ])
);
